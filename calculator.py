a = int(input("Enter first number: "))
b = int(input("Enter second number: "))

c = input("Enter operation to perform:\n+ for addition\n* for multiplication\n- for subtraction\n/ for division: ")

if c== "+":
    print(a+b)
if c== "*":
    print(a*b)
if c== "-":
    print(a-b)
if c== "/":
    print(a/b)
    
    
    